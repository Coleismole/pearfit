// Bundles the API handlers (engine/api/) into website/api/, the Vercel project's function directory.
// The Vercel project is rooted at website/, so it cannot import engine/ at runtime: the functions ship as
// self-contained bundles, committed like website/api/scraper. Re-run this after changing engine/api, engine/src
// or engine/cli, and commit the output.
//
//   npm run build:api   (from engine/)
//
// esbuild comes from webscraper's install (the same way scripts/assemble-site.mjs gets it), so the engine
// has no extra dependency. Run `npm install` in webscraper/ first if it is missing.
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const engine = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repo = path.resolve(engine, '..');
const require = createRequire(path.join(repo, 'webscraper', 'package.json'));
const esbuild = require('esbuild');

const functions = ['recommend', 'candidates'];
for (const name of functions) {
  await esbuild.build({
    entryPoints: [path.join(engine, 'api', `${name}.ts`)],
    bundle: true,
    platform: 'node',
    target: 'node22',
    format: 'cjs',
    outfile: path.join(repo, 'website', 'api', `${name}.js`),
    banner: { js: `// Generated by engine/scripts/build-api.mjs from engine/api/${name}.ts. Do not edit by hand.` },
    // Vercel calls module.exports as the handler; esbuild puts an `export default` under .default.
    footer: { js: 'module.exports = module.exports.default;' },
    logLevel: 'info',
  });
}
